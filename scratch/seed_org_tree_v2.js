let globalCounter = 1;
function generateNode(key, value, level = 0) {
  let type = "وحدة";
  if (level === 0) type = "إدارة عليا";
  else if (key.includes("مكتب")) type = "مكتب";
  else if (key.includes("إدارة")) type = "إدارة";
  else if (key.includes("دائرة")) type = "دائرة";
  else if (key.includes("قسم")) type = "قسم";
  else if (level === 1 && !key.includes("المدير العام")) type = "إدارة عليا";
  
  const node = {
    id: `node-${Date.now()}-${globalCounter++}`,
    name: key,
    type: type,
    children: []
  };
  
  for (const childKey in value) {
    node.children.push(generateNode(childKey, value[childKey], level + 1));
  }
  return node;
}

const rootNodes = [];
for (const key in orgStructure) {
  rootNodes.push(generateNode(key, orgStructure[key], 0));
}

// Ensure it has a single root node for the tree component
let finalTree = rootNodes[0];
if (rootNodes.length > 1) {
  finalTree = {
    id: "root-litc",
    name: "مؤسسة LITC",
    type: "إدارة عليا",
    children: rootNodes
  };
}

async function main() {
  await prisma.systemSetting.upsert({
    where: { settingKey: 'LITC_ORG_TREE_SNAPSHOT' },
    create: {
      settingKey: 'LITC_ORG_TREE_SNAPSHOT',
      settingValue: JSON.stringify(finalTree),
      description: 'Global Organizational Tree Visual Layout'
    },
    update: { settingValue: JSON.stringify(finalTree) }
  });
  console.log("Tree successfully saved to database!");
}

main().then(() => process.exit(0)).catch(e => console.error(e));
