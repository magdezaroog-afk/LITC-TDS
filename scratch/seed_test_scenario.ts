import { PrismaClient } from '@prisma/client';
import argon2 from 'argon2';

const prisma = new PrismaClient();

async function main() {
  const passwordHash = await argon2.hash('123456');

  // 1. Create IT Support Department
  let itDept = await prisma.department.findUnique({ where: { name: 'IT Support' } });
  if (!itDept) {
    itDept = await prisma.department.create({
      data: {
        name: 'IT Support',
        assignmentMode: 'PULL',
        routingStrategy: 'POOL'
      }
    });
  }

  // 2. Create Operator B
  let opUser = await prisma.user.findUnique({ where: { email: 'operator@litc.ly' } });
  if (opUser) {
    opUser = await prisma.user.update({
      where: { email: 'operator@litc.ly' },
      data: { role: { connect: { name: 'employee' } }, department: { connect: { id: itDept.id } } }
    });
  } else {
    opUser = await prisma.user.create({
      data: {
        email: 'operator@litc.ly',
        username: 'operator_ahmed',
        password: passwordHash,
        fullName: 'أحمد التشغيلي',
        role: { connect: { name: 'employee' } },
        department: { connect: { id: itDept.id } },
        jobTitle: 'دعم فني',
      }
    });
  }

  // 3. Assign Operational Interface
  const existingUi = await prisma.interface.findFirst({ where: { userId: opUser.id, interfaceType: 'OPERATIONAL' } });
  if (!existingUi) {
    await prisma.interface.create({
      data: {
        name: 'IT Operations Desk',
        interfaceType: 'OPERATIONAL',
        userId: opUser.id,
        isAutoGenerated: true
      }
    });
  }

  // 4. Create Regular Employee A
  let empUser = await prisma.user.findUnique({ where: { email: 'employee@litc.ly' } });
  if (empUser) {
    empUser = await prisma.user.update({
      where: { email: 'employee@litc.ly' },
      data: { role: { connect: { name: 'employee' } }, department: { disconnect: true } }
    });
  } else {
    empUser = await prisma.user.create({
      data: {
        email: 'employee@litc.ly',
        username: 'employee_salem',
        password: passwordHash,
        fullName: 'سالم الموظف',
        role: { connect: { name: 'employee' } },
        jobTitle: 'موظف مبيعات',
      }
    });
  }

  console.log('----------------------------------------');
  console.log('✅ TEST SCENARIO SEEDED SUCCESSFULLY!');
  console.log('----------------------------------------');
  console.log('👤 [الموظف العادي - مرسل الطلب]');
  console.log('📧 الإيميل: employee@litc.ly');
  console.log('🔑 كلمة المرور: 123456');
  console.log('----------------------------------------');
  console.log('🛠️ [الموظف التشغيلي - مستقبل الطلب]');
  console.log('📧 الإيميل: operator@litc.ly');
  console.log('🔑 كلمة المرور: 123456');
  console.log('----------------------------------------');
}

main()
  .catch(e => {
    console.error('Error seeding test scenario:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
