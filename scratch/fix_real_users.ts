import { PrismaClient } from '@prisma/client';
import argon2 from 'argon2';

const prisma = new PrismaClient();

async function main() {
  // 1. Delete interfaces of dummy users first
  const dummyUsers = await prisma.user.findMany({
    where: { email: { in: ['operator@litc.ly', 'employee@litc.ly'] } }
  });
  
  for (const du of dummyUsers) {
    await prisma.interface.deleteMany({
      where: { userId: du.id }
    });
  }

  // 2. Delete dummy users
  await prisma.user.deleteMany({
    where: { email: { in: ['operator@litc.ly', 'employee@litc.ly'] } }
  });
  console.log('Dummy users and their interfaces deleted.');

  // 3. Make Majdi an operational user, ensure he has an interface, and reset password
  const passwordHash = await argon2.hash('123456');
  const majdi = await prisma.user.findUnique({ where: { email: 'majdi.alzarrouk@litc.ly' } });
  
  if (majdi) {
    // Reset password so user can login easily
    await prisma.user.update({
      where: { email: 'majdi.alzarrouk@litc.ly' },
      data: { password: passwordHash }
    });
    console.log('Password reset to 123456 for majdi.alzarrouk@litc.ly');

    // Check if he has an operational interface
    const existingUi = await prisma.interface.findFirst({
      where: { userId: majdi.id, interfaceType: 'OPERATIONAL' }
    });

    if (!existingUi) {
      await prisma.interface.create({
        data: {
          name: 'IT Support Operations',
          interfaceType: 'OPERATIONAL',
          userId: majdi.id,
          isAutoGenerated: true,
          departmentId: majdi.departmentId
        }
      });
      console.log('Created Operational UI for Majdi.');
    }
  }
}

main()
  .catch(e => console.error(e))
  .finally(() => prisma.$disconnect());
