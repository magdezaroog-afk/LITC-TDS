function inferType(name) {
  if (name.includes('مجلس الإدارة') || name.includes('المدير العام')) return 'إدارة عليا';
  if (name.includes('إدارة')) return 'إدارة';
  if (name.includes('دائرة')) return 'إدارة';
  if (name.includes('مكتب')) return 'مكتب';
  if (name.includes('قسم') || name.includes('مركز')) return 'قسم';
  if (name.includes('وحدة') || name.includes('محطة')) return 'وحدة';
  return 'قسم';
}

function convertToOrgNode(key, nodeObj) {
  const childrenKeys = Object.keys(nodeObj);
  const type = inferType(key);
  return {
    id: `node_${Math.random().toString(36).substr(2, 9)}`,
    name: key,
    type: type,
    children: childrenKeys.map(childKey => convertToOrgNode(childKey, nodeObj[childKey]))
  };
}

const tree = convertToOrgNode('مجلس الإدارة', orgStructure['مجلس الإدارة']);

async function seedTree() {
  const jsonTree = JSON.stringify(tree);
  
  await prisma.systemSetting.upsert({
    where: { settingKey: 'LITC_ORG_TREE_SNAPSHOT' },
    update: { settingValue: jsonTree },
    create: { settingKey: 'LITC_ORG_TREE_SNAPSHOT', settingValue: jsonTree, description: 'LITC Institutional Org Tree' }
  });
  
  console.log("Tree successfully saved to database!");
  process.exit(0);
}

seedTree();
